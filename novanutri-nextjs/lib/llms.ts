import { getSiteMessages } from "@/content/site";
import {
  APP_STORE_URL,
  PLAY_STORE_URL,
  SHOP_PRICE_COUNTRIES,
  SITE_ORIGIN,
  US_PRICE_COUNTRY,
} from "@/lib/seo";

const SHOP_COUNTRY_LIST = SHOP_PRICE_COUNTRIES.map((country) => country.name).join(", ");

function links(): string {
  return [
    `- Home: ${SITE_ORIGIN}/`,
    `- Collaborations: ${SITE_ORIGIN}/collaborations`,
    `- Privacy policy: ${SITE_ORIGIN}/privacy`,
    `- Terms: ${SITE_ORIGIN}/terms`,
    `- Software license: ${SITE_ORIGIN}/license`,
    `- Full notes for assistants: ${SITE_ORIGIN}/llms-full.txt`,
    `- App Store (iOS): ${APP_STORE_URL}`,
    `- Google Play (Android): ${PLAY_STORE_URL}`,
    `- Contact: info@riov.app`,
  ].join("\n");
}

/** Short /llms.txt. English, the site default. */
export function llmsText(): string {
  const t = getSiteMessages("en");
  return `# Riov

> ${t.meta.description}

Riov is a meal-planning app for iPhone and Android, made by Cristian Dorultan (Sitges, Barcelona, Spain) and published at ${SITE_ORIGIN}. It is a planning tool, not a medical device.

## Who it is for

People who want a Mediterranean, vegetarian, vegan, pescatarian or standard meal plan, a shopping list made from that plan, and a supermarket cost before they shop.

## Real supermarket prices

Real supermarket prices are available in Europe and the United States.

Riov has its own shop prices for the 27 European Union countries and the United Kingdom: ${SHOP_COUNTRY_LIST}.

The ${US_PRICE_COUNTRY.name} is included as well, including its 50 states. When a product has no local supermarket price, Riov shows a labeled estimate based on Spanish prices.

## Languages

English, Spanish, Catalan, French, Italian, Romanian and Danish. The website and the app use the same seven languages.

## Units

The app can show metric units or US customary units.

## Pricing

The app is currently free. Paid features are not offered yet (Privacy Policy and Terms, last updated 18 November 2026).

Brands that place a product inside a meal plan pay a flat €0.01 per appearance per item. Clicks on the product link are not charged. See ${SITE_ORIGIN}/collaborations.

## Links

${links()}
`;
}

/** Longer /llms-full.txt, including the on-page FAQ. */
export function llmsFullText(): string {
  const t = getSiteMessages("en");
  const faq = t.faq.items.map((item) => `### ${item.q}\n\n${item.a}`).join("\n\n");
  return `# Riov

> ${t.meta.description}

${t.hero.body}

Riov is a meal-planning app for iPhone and Android. The website is ${SITE_ORIGIN}. The publisher is Cristian Dorultan, operating under the trade name Riov, in Sitges, Barcelona, Spain. Email: info@riov.app. Riov is not an incorporated company. Riov is not a medical device and does not give medical, dietetic or nutritional advice. Nutrition figures and prices are estimates.

## Who it is for

Households that want help deciding what to cook, what it will cost, and what to buy. Plans can follow a Mediterranean pattern or another diet type, with a daily calorie target on custom plans.

## What the app does

- Mediterranean meal plans, and custom plans, for any stretch from 1 day up to 31 days (a week or about a month).
- Diet types: Mediterranean, standard (omnivore), pescatarian, vegetarian and vegan.
- A daily calorie target on custom plans. Guided Mediterranean plans manage calories from the guidelines.
- A recipe library with estimated cost per person and in total, nutrition, allergens, equipment, prep time and servings.
- Ratings, written reviews and review photos. People can submit recipes, which are checked before they are published.
- An AI food scanner: photograph a meal or ingredients and the app estimates what it is and its nutrition. Results are estimates.
- A nutrition diary on the home screen (today's calories and macros against a target). Logging health data needs explicit consent.
- A shopping list (the Basket) built from the meal plan, with PDF export or a text copy.
- Real supermarket prices in Europe and the United States. Own shop prices cover ${SHOP_COUNTRY_LIST}. The ${US_PRICE_COUNTRY.name}, including its 50 states, is included. A missing local price is shown as a labeled estimate based on Spanish prices. Riov does not sell groceries.
- Allergy and disliked-ingredient filters, applied when the person consents. Allergen data can be incomplete.
- Cooking mode with step-by-step instructions, photos and timers.
- Favourites, push notifications, and sign-in with email, Google, or a guest account.
- Metric or US customary units.
- Languages: English, Spanish, Catalan, French, Italian, Romanian and Danish.

Automatic meal plans are generated by rules in the app. The AI food scanner and translation send the photo or the recipe text to OpenAI. Allergies, diet and the diary are not sent to the AI provider.

## Pricing

The app is currently free. The Privacy Policy and the Terms (18 November 2026) say paid features are not currently offered.

Brand placements on the website: a flat €0.01 per appearance per item. Link clicks are not charged. ${SITE_ORIGIN}/collaborations

## Languages and countries

Website and app languages: English, Spanish, Catalan, French, Italian, Romanian, Danish.

Real supermarket prices: Europe and the United States. Own shop-price countries: ${SHOP_COUNTRY_LIST}. United States prices cover the 50 states.

## FAQ

${faq}

## Links

${links()}
`;
}
